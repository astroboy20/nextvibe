const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

export function findCountry(code: string | undefined | null): Country | undefined {
  return code ? BY_CODE.get(code.toUpperCase()) : undefined;
}

/**
 * The currency a country's banks settle in, or undefined when we don't have a
 * supported mapping. Undefined means "leave the current selection alone" —
 * guessing would be worse than showing whatever is already chosen.
 */
export function currencyForCountry(code: string | undefined | null): string | undefined {
  return findCountry(code)?.currency;
}
