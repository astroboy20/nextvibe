/**
 * Every ISO 3166-1 alpha-2 country, for the payout form's country select.
 *
 * Generated from the runtime's own ICU data (`Intl.DisplayNames` over every
 * two-letter region code, minus aggregates like EU/UN/ZZ) so the names and codes
 * are correct by construction rather than hand-typed. The currency map below is
 * the only hand-maintained part — extend it when a new currency is supported.
 *
 * Covers all countries, not just ones whose currency we support, because the
 * rail and the currency are independent: a SWIFT wire or a Wise/PayPal payout
 * can land anywhere, and an earlier version of this list held only 27 countries
 * — which silently made those rails unusable outside them. The country field was
 * free text before that, so restricting it was a regression.
 *
 * `currency` is present only where the country settles in one of the currencies
 * the ledger actually supports (see the backend's SUPPORTED_CURRENCIES). It is a
 * *hint* used to preselect the currency field when the country changes, never a
 * constraint — someone may hold a USD account at a bank outside the US, so the
 * currency select stays editable. Countries with no mapping leave the currency
 * selection untouched rather than guessing.
 */
export interface Country {
  /** ISO 3166-1 alpha-2. */
  code: string;
  name: string;
  /** ISO 4217 code, only when it is one this platform supports. */
  currency?: string;
}

